#!/usr/bin/env python3
r"""Build and embed a Puppy DTM device tree blob.

Typical use:
  python tools/dtm_build_dtb.py ^
    --dtc D:\work\rt-thread\bsp\rockchip\tools\dtc\windows\dtc.exe ^
    --dts core\dtm\boards\stm32f407-puppy.dts ^
    --dtb output\dtb\stm32f407-puppy.dtb ^
    --out-c core\dtm\ofw\dtm_dtb_board.c

The generated C file defines __dtm_dtb_blob and __dtm_dtb_blob_size.
Because xmake already compiles core/**/*.c, placing the output under
core/dtm/ofw makes the DTB part of the kernel image.
"""

import argparse
import os
import subprocess
import sys


def ensure_dir(path):
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.exists(directory):
        os.makedirs(directory)


def run_dtc(dtc, dts, dtb):
    ensure_dir(dtb)
    cmd = [dtc, "-I", "dts", "-O", "dtb", "-o", dtb, dts]
    subprocess.check_call(cmd)


def read_binary(path):
    with open(path, "rb") as f:
        return f.read()


def write_c_blob(data, out_c):
    ensure_dir(out_c)
    with open(out_c, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/dtm_build_dtb.py. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write("__attribute__((aligned(4), used, section(\".rodata.dtm_dtb\")))\n")
        f.write("const unsigned char __dtm_dtb_blob[] = {\n")
        for offset in range(0, len(data), 12):
            chunk = data[offset:offset + 12]
            values = ", ".join(f"0x{b:02x}" for b in chunk)
            f.write(f"    {values},\n")
        f.write("};\n\n")
        f.write("const unsigned int __dtm_dtb_blob_size = sizeof(__dtm_dtb_blob);\n")


def parse_args(argv):
    parser = argparse.ArgumentParser(description="Compile/embed a DTM DTB")
    parser.add_argument("--dtc", help="path to dtc.exe; required with --dts")
    parser.add_argument("--dts", help="input DTS file")
    parser.add_argument("--dtb", help="input/output DTB file")
    parser.add_argument(
        "--out-c",
        default=os.path.join("core", "dtm", "ofw", "dtm_dtb_board.c"),
        help="generated C source path",
    )
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv if argv is not None else sys.argv[1:])

    if args.dts:
        if not args.dtc:
            print("error: --dtc is required when --dts is used", file=sys.stderr)
            return 2
        if not args.dtb:
            base = os.path.splitext(os.path.basename(args.dts))[0]
            args.dtb = os.path.join("output", "dtb", base + ".dtb")
        run_dtc(args.dtc, args.dts, args.dtb)
    elif not args.dtb:
        print("error: pass either --dts or --dtb", file=sys.stderr)
        return 2

    data = read_binary(args.dtb)
    write_c_blob(data, args.out_c)
    print(f"embedded {args.dtb} ({len(data)} bytes) -> {args.out_c}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
